func TestLoadSettingsImportsOnceThenReadsOwnFiles(t *testing.T) {
	legacyDir := writeLegacy(t)
	dir := t.TempDir()

	s, _, imported, err := LoadSettings(dir, legacyDir, `C:\Downloads`)
	if err != nil || !imported || s.Appearance.Theme != "dark" {
		t.Fatalf("first load: imported=%v err=%v theme=%q", imported, err, s.Appearance.Theme)
	}

	s.Appearance.Theme = "light"
	if err := Save(filepath.Join(dir, SettingsFile), s); err != nil {
		t.Fatal(err)
	}
	s, p, imported, err := LoadSettings(dir, legacyDir, `C:\Downloads`)
	if err != nil || imported || s.Appearance.Theme != "light" {
		t.Fatalf("second load: imported=%v err=%v theme=%q", imported, err, s.Appearance.Theme)
	}
	if p.Paths.AudioDownloadDir != `D:\Music` {
		t.Errorf("preferences not kept: %+v", p.Paths)
	}
}

func TestLoadSettingsDefaultsAndMissingFields(t *testing.T) {
	dir := t.TempDir()
	s, p, imported, err := LoadSettings(dir, "", `C:\Downloads`)
	if err != nil || imported {
		t.Fatalf("imported=%v err=%v", imported, err)
	}
	if !reflect.DeepEqual(s, Normalize(DefaultSettings(`C:\Downloads`), `C:\Downloads`)) {
		t.Errorf("defaults differ: %+v", s)
	}
	if p.Recents.Recent == nil {
		t.Error("recents map is nil")
	}

	// A file written by an older version lacks new fields: they keep defaults.
	partial := `{"performance": {"maxConcurrency": 99}, "input": {"autoFillClipboard": false}}`
	if err := os.WriteFile(filepath.Join(dir, SettingsFile), []byte(partial), 0o644); err != nil {
		t.Fatal(err)
	}
	s, _, _, err = LoadSettings(dir, "", `C:\Downloads`)
	if err != nil {
		t.Fatal(err)
	}
	if s.Performance.MaxConcurrency != 32 {
		t.Errorf("concurrency not clamped: %d", s.Performance.MaxConcurrency)
	}
	if s.Input.AutoFillClipboard || !s.Input.GlobalShortcuts || s.Input.DefaultPreset != "best" {
		t.Errorf("input merged wrongly: %+v", s.Input)
	}
	if s.Output.DownloadDir != `C:\Downloads` || s.Performance.SplitPlaylistThreshold != 50 {
		t.Errorf("defaults lost: %q %d", s.Output.DownloadDir, s.Performance.SplitPlaylistThreshold)
	}
}

func TestAddRecent(t *testing.T) {
	p := DefaultPreferences()
	for _, path := range []string{"a", "b", "c", "d", "e", "f", "c"} {
		p.AddRecent("downloadDir", path)
	}
	want := []string{"c", "f", "e", "d", "b"}
	if got := p.Recents.Recent["downloadDir"]; !reflect.DeepEqual(got, want) {
		t.Errorf("recents %v, want %v", got, want)
	}
}
