func writeLegacy(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "config.store.json"), []byte(legacyConfigJSON), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "preferences.store.json"), []byte(legacyPreferencesJSON), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestImportLegacy(t *testing.T) {
	legacy, ok := ImportLegacy(writeLegacy(t), `C:\Downloads`)
	if !ok {
		t.Fatal("legacy config not imported")
	}
	s, p := legacy.Settings, legacy.Preferences

	checks := []struct {
		name      string
		got, want any
	}{
		{"theme", s.Appearance.Theme, "dark"},
		{"cookie browser", s.Auth.CookieBrowser, "firefox"},
		{"cookie file (null)", s.Auth.CookieFile, ""},
		{"proxy on because one is set", s.Network.EnableProxy, true},
		{"proxy", s.Network.Proxy, "socks5://127.0.0.1:1080"},
		{"auto fill", s.Input.AutoFillClipboard, false},
		{"prefer video", s.Input.PreferVideoInMixedLinks, true},
		{"new default preset", s.Input.DefaultPreset, "best"},
		{"new auto download", s.Input.AutoDownload, true},
		{"min size off", s.InputFilters.MinSize.Value == nil, true},
		{"max size", *s.InputFilters.MaxSize.Value, 2.0},
		{"max unit", s.InputFilters.MaxSize.Unit, "GB"},
		{"date mode (null)", s.InputFilters.DateFilter.Mode, ""},
		{"container", s.Output.Video.Container, "mkv"},
		{"remuxOnly becomes allowReencode", s.Output.Video.Policy, PolicyAllowReencode},
		{"audio keeps original", s.Output.Audio.Policy, PolicyNever},
		{"audio format", s.Output.Audio.Format, "opus"},
		{"add thumbnail", s.Output.AddThumbnail, false},
		{"download dir", s.Output.DownloadDir, `D:\Videos`},
		{"file template", s.Output.FileNameTemplate, "%(title)s.%(ext)s"},
		{"concurrency", s.Performance.MaxConcurrency, 4},
		{"split threshold", s.Performance.SplitPlaylistThreshold, 100},
		{"subtitles on", s.Subtitles.Enabled, true},
		{"subtitle languages", s.Subtitles.Languages, []string{"en", "zh-cn"}},
		{"json becomes json3", s.Subtitles.FormatPreference, []string{"json3", "srt"}},
		{"embed", s.Subtitles.EmbedSubtitles, false},
		{"translation", s.Translation, TranslationSettings{true, "https://api.deepseek.com", "deepseek-chat", "简体中文", false}},
		{"update app", s.Update.UpdateApp, false},
		{"tray", s.System.TrayEnabled, true},
		{"close behavior", s.System.CloseBehavior, CloseHide},
		{"notifications", s.Notifications.NotificationBehavior, NotifyOnBackground},
		{"disabled notifications", s.Notifications.DisabledNotifications, []string{"queueAdded"}},
		{"audio dir", p.Paths.AudioDownloadDir, `D:\Music`},
		{"video dir (null)", p.Paths.VideoDownloadDir, ""},
		{"video template", p.Paths.VideoDirectoryTemplate, "%(uploader)s"},
		{"recents", p.Recents.Recent["downloadDir"], []string{`D:\Videos`, `C:\Users\me\Downloads`}},
	}
	for _, c := range checks {
		if !reflect.DeepEqual(c.got, c.want) {
			t.Errorf("%s: got %#v, want %#v", c.name, c.got, c.want)
		}
	}
}

