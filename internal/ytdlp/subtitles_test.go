package ytdlp

import (
	"testing"

	"github.com/pandyzhou/youtube-dl-gui/internal/config"
)

// Ported from the subtitle tests in src-tauri/src/runners/ytdlp_runner.rs.

func subtitleSettings() config.SubtitleSettings {
	return config.DefaultSettings("/d").Subtitles
}

func inv(manual []string, auto []string) *SubtitleInventory {
	return &SubtitleInventory{ManualLanguages: manual, AutoLanguages: auto}
}

func TestSubtitlesDisabled(t *testing.T) {
	if args := SubtitleArgs(subtitleSettings(), inv([]string{"en"}, nil)); args != nil {
		t.Fatalf("args %q", args)
	}
}

func TestSubtitlesEnabledUsesDefaults(t *testing.T) {
	s := subtitleSettings()
	s.Enabled, s.Languages, s.FormatPreference = true, nil, nil
	expect(t, SubtitleArgs(s, inv([]string{"en"}, nil)),
		"--write-subs", "--embed-subs", "--no-write-auto-subs", "--no-write-subs", "--sub-format", "srt/vtt/ass/ttml/json3", "--sub-langs", "en")
}

func TestSubtitlesEmbedAndAutoGenerated(t *testing.T) {
	s := subtitleSettings()
	s.Enabled, s.IncludeAutoGenerated = true, true
	expect(t, SubtitleArgs(s, inv(nil, []string{"en"})),
		"--write-subs", "--embed-subs", "--no-write-auto-subs", "--no-write-subs", "--write-auto-subs", "--sub-format", "srt/vtt/ass/ttml/json3", "--sub-langs", "en")
}

func TestSubtitlesAllLanguages(t *testing.T) {
	s := config.SubtitleSettings{Enabled: true, Languages: []string{"all", "en"}, FormatPreference: []string{"srt", "vtt"}, IncludeAutoGenerated: true}
	expect(t, SubtitleArgs(s, inv([]string{"de"}, []string{"en"})),
		"--write-subs", "--no-embed-subs", "--sub-format", "srt/vtt/ass/ttml/json3", "--sub-langs", "de")
}

func TestSubtitlesTrimAndDedupe(t *testing.T) {
	s := subtitleSettings()
	s.Enabled, s.Languages = true, []string{" en ", "EN", "pt-BR", ""}
	if args := SubtitleArgs(s, inv([]string{"en", "pt-br"}, nil)); args[7] != "en,pt-br" {
		t.Fatalf("args %q", args)
	}
}

func TestSubtitlesLegacyJSON(t *testing.T) {
	s := subtitleSettings()
	s.Enabled, s.FormatPreference = true, []string{"json", "json3"}
	if args := SubtitleArgs(s, inv([]string{"en"}, nil)); args[5] != "json3/srt/vtt/ass/ttml" {
		t.Fatalf("args %q", args)
	}
}

func TestSubtitlesSkipped(t *testing.T) {
	s := subtitleSettings()
	s.Enabled, s.Languages = true, []string{"fr"}
	if args := SubtitleArgs(s, inv([]string{"en"}, nil)); args != nil {
		t.Errorf("unavailable language: %q", args)
	}
	s = subtitleSettings()
	s.Enabled = true
	if args := SubtitleArgs(s, inv(nil, []string{"en"})); args != nil {
		t.Errorf("auto captions while disabled: %q", args)
	}
	if args := SubtitleArgs(s, nil); args != nil {
		t.Errorf("no inventory: %q", args)
	}
}

func TestSubtitlesAutoSelection(t *testing.T) {
	s := subtitleSettings()
	s.Enabled, s.IncludeAutoGenerated = true, true
	cases := []struct {
		name   string
		manual []string
		auto   []string
		want   string
	}{
		{"manual and auto match", []string{"en"}, []string{"en"}, "en"},
		{"orig auto caption", nil, []string{"en-orig"}, "en-orig"},
		{"orig over the translated track", nil, []string{"en", "en-orig"}, "en-orig"},
		{"translations ignored", nil, []string{"en", "en-orig", "de", "fr"}, "en-orig"},
	}
	for _, c := range cases {
		args := SubtitleArgs(s, inv(c.manual, c.auto))
		if len(args) < 9 || args[4] != "--write-auto-subs" || args[8] != c.want {
			t.Errorf("%s: args %q", c.name, args)
		}
	}
}
