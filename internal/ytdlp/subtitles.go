package ytdlp

import (
	"sort"
	"strings"

	"github.com/pandyzhou/lumadl/internal/config"
)

// SubtitleArgs returns the subtitle options for a video with inventory, or
// nil when subtitles are off, the inventory is unknown, or none of the
// wanted languages exist. Auto captions are only taken when allowed and
// when they cover the same languages as the manual subtitles taken (or
// there are none), since yt-dlp cannot pick sources per language.
func SubtitleArgs(settings config.SubtitleSettings, inventory *SubtitleInventory) []string {
	if !settings.Enabled || inventory == nil {
		return nil
	}
	languages, includeAuto := resolveSubtitles(settings, *inventory)
	if len(languages) == 0 {
		return nil
	}
	args := []string{"--write-subs"}
	if settings.EmbedSubtitles {
		// Embed, then remove the separate subtitle files.
		args = append(args, "--embed-subs", "--no-write-auto-subs", "--no-write-subs")
	} else {
		args = append(args, "--no-embed-subs")
	}
	if includeAuto {
		args = append(args, "--write-auto-subs")
	}
	return append(args,
		"--sub-format", strings.Join(SanitizeSubtitleFormats(settings.FormatPreference), "/"),
		"--sub-langs", strings.Join(languages, ","))
}

func resolveSubtitles(settings config.SubtitleSettings, inventory SubtitleInventory) ([]string, bool) {
	manual := sanitizeList(inventory.ManualLanguages)
	preferredAuto := preferredAutoLanguages(sanitizeList(inventory.AutoLanguages))

	requested := sanitizeList(settings.Languages)
	if len(requested) == 0 {
		requested = []string{"en"}
	}
	wantsAll := contains(requested, "all")

	var manualLanguages []string
	if wantsAll {
		manualLanguages = manual
	} else {
		bases := map[string]bool{}
		for _, l := range manual {
			bases[subtitleBase(l)] = true
		}
		for _, l := range requested {
			if bases[subtitleBase(l)] {
				manualLanguages = append(manualLanguages, l)
			}
		}
	}

	var autoLanguages []string
	if settings.IncludeAutoGenerated {
		if wantsAll {
			for _, p := range preferredAuto {
				autoLanguages = append(autoLanguages, p.request)
			}
		} else {
			autoLanguages = resolveAutoLanguages(requested, preferredAuto)
		}
	}

	safeForAuto := false
	if len(autoLanguages) > 0 {
		manualBases := subtitleBases(manualLanguages)
		safeForAuto = len(manualBases) == 0 || equalStrings(manualBases, subtitleBases(autoLanguages))
	}
	if !safeForAuto {
		return manualLanguages, false
	}
	return unique(append(append([]string{}, manualLanguages...), autoLanguages...)), true
}

type autoPreference struct{ request, base string }

// preferredAutoLanguages picks one auto caption per language, the plain
// one over its "-orig" twin. When any "-orig" exists, languages without
// one are machine translations and are left out.
func preferredAutoLanguages(automatic []string) []autoPreference {
	type pair struct{ plain, orig string }
	grouped := map[string]*pair{}
	for _, l := range automatic {
		base := subtitleBase(l)
		if grouped[base] == nil {
			grouped[base] = &pair{}
		}
		if strings.HasSuffix(l, "-orig") {
			grouped[base].orig = l
		} else {
			grouped[base].plain = l
		}
	}
	hasOrig := false
	for _, p := range grouped {
		hasOrig = hasOrig || p.orig != ""
	}
	var out []autoPreference
	for base, p := range grouped {
		if hasOrig && p.orig == "" {
			continue
		}
		request := p.plain
		if request == "" {
			request = p.orig
		}
		out = append(out, autoPreference{request: request, base: base})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].base < out[j].base })
	return out
}

func resolveAutoLanguages(requested []string, automatic []autoPreference) []string {
	byBase := map[string]string{}
	for _, a := range automatic {
		byBase[a.base] = a.request
	}
	var out []string
	for _, l := range requested {
		if candidate, ok := byBase[subtitleBase(l)]; ok && !contains(out, candidate) {
			out = append(out, candidate)
		}
	}
	return out
}

// SanitizeSubtitleFormats puts the first known format first, then the
// other defaults, then unknown extras; "json" becomes "json3".
func SanitizeSubtitleFormats(formats []string) []string {
	var inputs []string
	for _, f := range sanitizeList(formats) {
		if f == "json" {
			f = "json3"
		}
		if !contains(inputs, f) {
			inputs = append(inputs, f)
		}
	}
	primary := config.DefaultSubtitleFormats[0]
	if len(inputs) > 0 {
		primary = inputs[0]
	}
	for _, f := range inputs {
		if contains(config.DefaultSubtitleFormats, f) {
			primary = f
			break
		}
	}
	ordered := []string{primary}
	for _, f := range config.DefaultSubtitleFormats {
		if !contains(ordered, f) {
			ordered = append(ordered, f)
		}
	}
	for _, f := range inputs {
		if !contains(ordered, f) {
			ordered = append(ordered, f)
		}
	}
	return ordered
}

func subtitleBase(language string) string {
	return strings.ToLower(strings.TrimSuffix(strings.TrimSpace(language), "-orig"))
}

func subtitleBases(languages []string) []string {
	var out []string
	for _, l := range languages {
		if b := subtitleBase(l); !contains(out, b) {
			out = append(out, b)
		}
	}
	return out
}

// sanitizeList trims, lowercases and de-duplicates, dropping empty items.
func sanitizeList(items []string) []string {
	var out []string
	for _, item := range items {
		item = strings.ToLower(strings.TrimSpace(item))
		if item != "" && !contains(out, item) {
			out = append(out, item)
		}
	}
	return out
}

func unique(items []string) []string {
	var out []string
	for _, item := range items {
		if !contains(out, item) {
			out = append(out, item)
		}
	}
	return out
}

func contains(items []string, s string) bool {
	for _, item := range items {
		if item == s {
			return true
		}
	}
	return false
}

func equalStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}
